describe('日付・数・支払期限の読み取り（単体）', () => {
  const today = '2026-11-13'
  it('[REQ-009] 日付：全角・ハイフン・和暦・年なし・8 桁を受け、実在しない日と改元の境をまたぐ日は受けない', () => {
    const ymd = (s: string) => { const r = readDate(s, today); return r.kind === 'ok' ? r.ymd : r.kind }
    expect(ymd('2026/11/30')).toBe('2026-11-30')
    expect(ymd('2026年11月30日')).toBe('2026-11-30')
    expect(ymd('２０２６‐１１‐３０')).toBe('2026-11-30')
    expect(ymd('11月30日')).toBe('2026-11-30')
    expect(ymd('20261130')).toBe('2026-11-30')
    expect(ymd('令和8年11月30日')).toBe('2026-11-30')
    expect(ymd('R8.11.30')).toBe('2026-11-30')
    expect(ymd('令和元年5月1日')).toBe('2019-05-01')
    expect(ymd('平成31年4月30日')).toBe('2019-04-30')
    expect(ymd('平成31年5月1日')).toBe('bad')
    expect(ymd('令和元年4月30日')).toBe('bad')
    expect(ymd('2026/11/31')).toBe('bad')
    expect(ymd('2月29日')).toBe('bad')
    expect(ymd('')).toBe('empty')
    expect(ymd('あした')).toBe('bad')
  })
  it('[REQ-009] 数：全角・桁区切り・「円」を受け、0 以下と上限超えと文字は受けない。空は 0 にしない', () => {
    expect(readYen('１２０，０００円', MAX_AMOUNT)).toEqual({ kind: 'ok', value: 120000 })
    expect(readYen('', MAX_AMOUNT)).toEqual({ kind: 'empty' })
    expect(readYen('-5', MAX_AMOUNT)).toEqual({ kind: 'bad' })
    expect(readYen(String(MAX_AMOUNT + 1), MAX_AMOUNT)).toEqual({ kind: 'over' })
    expect(readQuantity('0.5', MAX_QUANTITY)).toEqual({ kind: 'ok', value: 0.5 })
    expect(readQuantity('0', MAX_QUANTITY)).toEqual({ kind: 'bad' })
    expect(readQuantity('1.234', MAX_QUANTITY)).toEqual({ kind: 'bad' })
    expect(readQuantity('', MAX_QUANTITY)).toEqual({ kind: 'empty' })
  })
  it('[REQ-014] 支払期限：締め日を過ぎたら翌月分。月末・月に無い日は月末に寄せる。年またぎ', () => {
    const t = (closingDay: 'end' | number, payMonthsLater: 0 | 1 | 2, payDay: 'end' | number) => ({ closingDay, payMonthsLater, payDay })
    expect(dueDateFor('2026-11-13', t('end', 1, 'end'))).toBe('2026-12-31')
    expect(dueDateFor('2026-11-13', t(20, 1, 'end'))).toBe('2026-12-31')
    expect(dueDateFor('2026-11-20', t(20, 1, 'end'))).toBe('2026-12-31')
    expect(dueDateFor('2026-11-21', t(20, 1, 'end'))).toBe('2027-01-31')
    expect(dueDateFor('2026-11-30', t('end', 2, 10))).toBe('2027-01-10')
    expect(dueDateFor('2026-12-15', t('end', 1, 'end'))).toBe('2027-01-31')
    expect(dueDateFor('2027-01-10', t('end', 1, 'end'))).toBe('2027-02-28')
    expect(dueDateFor('2027-01-10', t('end', 1, 31))).toBe('2027-02-28')
    expect(dueDateFor('2026-11-10', t('end', 0, 'end'))).toBe('2026-11-30')
  })
})

